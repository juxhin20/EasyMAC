import AppKit
import Observation

struct ClipItem: Identifiable, Equatable {
    enum Kind: Equatable {
        case text(String)
        case link(URL)
        case image(NSImage)
        case files([URL])
    }

    let id: UUID
    let kind: Kind
    let date: Date
    let sourceBundleID: String?

    init(id: UUID = UUID(), kind: Kind, date: Date, sourceBundleID: String?) {
        self.id = id
        self.kind = kind
        self.date = date
        self.sourceBundleID = sourceBundleID
    }

    var label: String {
        switch kind {
        case .text: "Text"
        case .link: "Link"
        case .image: "Image"
        case .files(let urls): urls.count == 1 ? "File" : "\(urls.count) Files"
        }
    }

    var searchText: String {
        switch kind {
        case .text(let s): s
        case .link(let u): u.absoluteString
        case .image: "image"
        case .files(let urls): urls.map(\.lastPathComponent).joined(separator: " ")
        }
    }

    static func == (a: ClipItem, b: ClipItem) -> Bool { a.id == b.id }

    /// Same content (used to move a re-copied item to the front instead of duplicating it).
    func sameContent(as other: ClipItem) -> Bool {
        switch (kind, other.kind) {
        case let (.text(a), .text(b)): a == b
        case let (.link(a), .link(b)): a == b
        case let (.files(a), .files(b)): a == b
        case let (.image(a), .image(b)): a.size == b.size && a.tiffRepresentation?.count == b.tiffRepresentation?.count
        default: false
        }
    }
}

/// Clipboard history. In memory only by default; with "Keep history" set to N days it is saved to
/// Application Support/EasyMAC/Clipboard (index.json + PNGs, owner-only permissions) and items older
/// than N days are dropped. Polls `changeCount` twice a second — the only way macOS offers — and skips
/// anything password managers mark as concealed.
@MainActor @Observable
final class ClipboardHistory {
    private(set) var items: [ClipItem] = []

    @ObservationIgnored private let settings = Settings.shared
    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var lastChange = NSPasteboard.general.changeCount
    @ObservationIgnored private var ignoreChange: Int?
    @ObservationIgnored private var saveTask: Task<Void, Never>?
    @ObservationIgnored private var loaded = false
    @ObservationIgnored private var reading = false

    private static var directory: URL {
        let base = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask).first
            ?? URL(fileURLWithPath: NSHomeDirectory()).appendingPathComponent("Library/Application Support")
        return base.appendingPathComponent("EasyMAC/Clipboard", isDirectory: true)
    }

    private nonisolated static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "com.typeit4me.clipping", "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type", "com.apple.is-remote-clipboard.ignore",
    ]

    func setEnabled(_ enabled: Bool) {
        timer?.invalidate()
        timer = nil
        guard enabled else { return }
        if !loaded {
            loaded = true
            load()
        }
        lastChange = NSPasteboard.general.changeCount
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.2
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func poll() {
        guard !reading else { return } // a slow read is still running; check again when it's done
        let change = NSPasteboard.general.changeCount
        guard change != lastChange else { return }
        lastChange = change
        if change == ignoreChange { return }

        let source = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        if let source, settings.excludedBundleIDs.contains(source) { return }

        // Read off the main thread: a clipboard coming from the iPhone (Universal Clipboard) is fetched
        // over the air when it's first read, and that can hang ~10 s — it froze all of EasyMAC.
        reading = true
        Self.readQueue.async {
            let kind = Self.readKind(NSPasteboard.general)
            DispatchQueue.main.async {
                MainActor.assumeIsolated { self.finishRead(kind, source: source) }
            }
        }
    }

    private func finishRead(_ kind: ClipItem.Kind?, source: String?) {
        reading = false
        guard let kind else { return }
        let item = ClipItem(kind: kind, date: Date(), sourceBundleID: source)
        items.removeAll { $0.sameContent(as: item) }
        items.insert(item, at: 0)
        if items.count > settings.clipboardLimit { items.removeLast(items.count - settings.clipboardLimit) }
        prune()
        scheduleSave()
    }

    private nonisolated static let readQueue = DispatchQueue(label: "com.appalbania.easymac.clipboard-read", qos: .userInitiated)

    private nonisolated static func readKind(_ pasteboard: NSPasteboard) -> ClipItem.Kind? {
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: skippedTypes) else { return nil }
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            return .files(urls)
        }
        if types.contains(where: { $0.contains("png") || $0.contains("tiff") || $0.contains("jpeg") }),
           !types.contains(NSPasteboard.PasteboardType.string.rawValue), let image = NSImage(pasteboard: pasteboard) {
            return .image(image)
        }
        if let string = pasteboard.string(forType: .string), !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            if let url = URL(string: string.trimmingCharacters(in: .whitespacesAndNewlines)),
               let scheme = url.scheme, ["http", "https"].contains(scheme), !string.contains(" ") {
                return .link(url)
            }
            return .text(string)
        }
        return nil
    }

    // MARK: - Persistence (only when "Keep history" > 0 days)

    private struct Stored: Codable {
        var id: UUID
        var date: Date
        var source: String?
        var type: String
        var text: String?
        var paths: [String]?
        var image: String?
    }

    func retentionChanged() {
        if settings.clipboardRetentionDays == 0 {
            try? FileManager.default.removeItem(at: Self.directory)
        } else {
            prune()
            scheduleSave()
        }
    }

    private func prune() {
        let days = settings.clipboardRetentionDays
        guard days > 0 else { return }
        let cutoff = Date().addingTimeInterval(-Double(days) * 86_400)
        items.removeAll { $0.date < cutoff }
    }

    private func scheduleSave() {
        guard settings.clipboardRetentionDays > 0 else { return }
        saveTask?.cancel()
        let snapshot = items
        saveTask = Task {
            try? await Task.sleep(for: .seconds(1))
            guard !Task.isCancelled else { return }
            Self.save(snapshot)
        }
    }

    private static func save(_ items: [ClipItem]) {
        let fm = FileManager.default
        let dir = directory
        try? fm.createDirectory(at: dir, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
        var stored: [Stored] = []
        var keepImages = Set<String>()
        for item in items {
            var entry = Stored(id: item.id, date: item.date, source: item.sourceBundleID, type: "text")
            switch item.kind {
            case .text(let s): entry.text = s
            case .link(let u): entry.type = "link"; entry.text = u.absoluteString
            case .files(let urls): entry.type = "files"; entry.paths = urls.map(\.path)
            case .image(let image):
                entry.type = "image"
                let name = item.id.uuidString + ".png"
                let url = dir.appendingPathComponent(name)
                if !fm.fileExists(atPath: url.path), let tiff = image.tiffRepresentation,
                   let png = NSBitmapImageRep(data: tiff)?.representation(using: .png, properties: [:]) {
                    try? png.write(to: url, options: .atomic)
                    try? fm.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path) // owner-only
                }
                entry.image = name
                keepImages.insert(name)
            }
            stored.append(entry)
        }
        if let data = try? JSONEncoder().encode(stored) {
            let index = dir.appendingPathComponent("index.json")
            try? data.write(to: index, options: .atomic)
            try? fm.setAttributes([.posixPermissions: 0o600], ofItemAtPath: index.path)
        }
        // Remove images of items that were deleted or expired.
        for name in (try? fm.contentsOfDirectory(atPath: dir.path)) ?? [] where name.hasSuffix(".png") && !keepImages.contains(name) {
            try? fm.removeItem(at: dir.appendingPathComponent(name))
        }
    }

    // MARK: - Handoff across a restart (updates) in "until restart" mode

    private static var handoffMarker: URL { directory.appendingPathComponent("handoff") }
    private static var appVersion: String {
        (Bundle.main.object(forInfoDictionaryKey: "CFBundleVersion") as? String) ?? ""
    }

    /// The marker holds the build that wrote it. It's valid for 10 minutes after quitting, or at any
    /// time when a different build reads it — an update installed while EasyMAC was closed (Sparkle
    /// "install on quit") must not lose the history however late EasyMAC is opened again.
    private static var handoffIsValid: Bool {
        let fm = FileManager.default
        guard let date = (try? fm.attributesOfItem(atPath: handoffMarker.path))?[.modificationDate] as? Date else { return false }
        if Date().timeIntervalSince(date) < 600 { return true }
        let writer = (try? String(contentsOf: handoffMarker, encoding: .utf8)) ?? ""
        return !writer.isEmpty && writer != appVersion
    }

    /// Runs at every launch, even with clipboard history off: in memory-only mode nothing may
    /// survive on disk except an update handoff, and nothing at all when disabled.
    static func cleanUpStaleData(enabled: Bool, retentionDays: Int) {
        let fm = FileManager.default
        guard fm.fileExists(atPath: directory.path) else { return }
        if !enabled {
            try? fm.removeItem(at: directory)
            return
        }
        guard retentionDays == 0 else { return }
        if !handoffIsValid { try? fm.removeItem(at: directory) }
    }

    /// Called when EasyMAC quits. In memory-only mode the history is written once so an update /
    /// quick relaunch can pick it up; it is read back on the next launch and deleted right away.
    func saveForRelaunch() {
        saveTask?.cancel()
        guard settings.clipboardEnabled, !items.isEmpty else { return }
        Self.save(items)
        if settings.clipboardRetentionDays == 0 {
            try? Data(Self.appVersion.utf8).write(to: Self.handoffMarker)
        }
    }

    private func load() {
        let fm = FileManager.default
        var isHandoff = false
        if settings.clipboardRetentionDays == 0 {
            isHandoff = Self.handoffIsValid
            if !isHandoff {
                try? fm.removeItem(at: Self.directory) // stale memory-only data never lingers
                return
            }
        }
        defer {
            if isHandoff { try? fm.removeItem(at: Self.directory) }
        }
        guard let data = try? Data(contentsOf: Self.directory.appendingPathComponent("index.json")),
              let stored = try? JSONDecoder().decode([Stored].self, from: data) else { return }
        items = stored.compactMap { entry in
            let kind: ClipItem.Kind?
            switch entry.type {
            case "link": kind = entry.text.flatMap(URL.init(string:)).map { .link($0) }
            case "files": kind = entry.paths.map { .files($0.map { URL(fileURLWithPath: $0) }) }
            case "image": kind = entry.image.flatMap { NSImage(contentsOf: Self.directory.appendingPathComponent($0)) }.map { .image($0) }
            default: kind = entry.text.map { .text($0) }
            }
            return kind.map { ClipItem(id: entry.id, kind: $0, date: entry.date, sourceBundleID: entry.source) }
        }
        prune()
        Log.app.notice("Clipboard: restored \(self.items.count) item(s)\(isHandoff ? " after relaunch" : "", privacy: .public)")
    }

    /// Puts an item back on the clipboard (without re-adding it as a new entry).
    func copy(_ item: ClipItem) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        switch item.kind {
        case .text(let s): pasteboard.setString(s, forType: .string)
        case .link(let u):
            pasteboard.writeObjects([u as NSURL])
            pasteboard.setString(u.absoluteString, forType: .string)
        case .image(let image): pasteboard.writeObjects([image])
        case .files(let urls): pasteboard.writeObjects(urls.map { $0 as NSURL })
        }
        ignoreChange = pasteboard.changeCount
        lastChange = pasteboard.changeCount
        // Move to front: it's the most recent thing on the clipboard again.
        if let index = items.firstIndex(of: item) {
            items.remove(at: index)
            items.insert(item, at: 0)
        }
    }

    func remove(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        scheduleSave()
    }

    func clear() {
        items.removeAll()
        scheduleSave()
    }

    /// ⌘V into the app that is frontmost (EasyMAC never activates, so that's the app you were in).
    static func pasteIntoFrontApp() {
        let source = CGEventSource(stateID: .combinedSessionState)
        for down in [true, false] {
            guard let event = CGEvent(keyboardEventSource: source, virtualKey: 9, keyDown: down) else { continue } // V
            event.flags = .maskCommand
            event.post(tap: .cgAnnotatedSessionEventTap)
        }
    }
}
